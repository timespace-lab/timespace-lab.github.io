    page.click('[data-act=ev-save]')
    check('사진 삭제(사진 없는 사건도 표시)', page.evaluate(f'evById("{eid["인천상륙작전"]}").photo') is None and page.is_visible('.cardA .noph'))
    # 같은 날짜 순서 조정
    page.evaluate('''() => { const a=WS.tl.events.find(e=>e.t==="서울 수복"); a.d={y:1950,m:9,d:15}; touch("tl"); render(); }''')
    o1 = page.evaluate('sorted().map(e=>e.t).slice(0,2)')
    page.evaluate(f'ACT["ev-sel"]("{eid["서울 수복"]}"); render()')
    page.click('[data-act=ev-up]')
    o2 = page.evaluate('sorted().map(e=>e.t).slice(0,2)')
    check('같은 날짜 사건 순서 조정', o1 != o2 and set(o1) == set(o2), f'{o1} → {o2}')
    # 연표 사건을 지도에서 확인
    page.evaluate(f'ACT["ev-sel"]("{eid["인천상륙작전"]}"); render()')
    page.click('[data-act=ev-onmap]')
    page.wait_for_selector('#maparea')
    check('연표 사건 → 지도에서 해당 핀 강조', page.evaluate('focusPinId()') == ids['인천'])
    # 핀 → 연표 사건 만들기
    page.evaluate(f'selectPin("{ids["부산"]}"); render()')
    page.click('[data-act=ev-from-pin]')
    page.fill('#f-y', '1950'); page.fill('#f-m', '8'); page.fill('#f-d', '18')
    page.click('[data-act=ev-save]')
    check('지도 핀으로 연표 사건 만들기(연결 유지)', page.evaluate(f'eventsOfPin("{ids["부산"]}").length') == 1)
