"""로그인 없이: 지도 핀·경로, 연표 사건·사진·디자인 전환, 새로고침 복구"""
import json, sys, os, time
from playwright.sync_api import sync_playwright
BASE = sys.argv[1]
SHOTS = sys.argv[2]
IMG = sys.argv[3]
results = []
def check(name, cond, detail=''):
    results.append((name, bool(cond), detail)); print(('PASS ' if cond else 'FAIL ') + name + (' · ' + str(detail) if detail else ''))

with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 1440, 'height': 900}, accept_downloads=True)
    page = ctx.new_page()
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('console', lambda m: errors.append('console:' + m.text) if m.type == 'error' and 'Failed to load resource' not in m.text and 'ERR_' not in m.text else None)
    page.goto(BASE + '/index.html')
    page.wait_for_selector('.hero')
    page.screenshot(path=f'{SHOTS}/01-home.png', full_page=False)
    check('홈 화면 표시', page.is_visible('text=시간을 읽고,'))
    # 지도 탐구 (로그인 없이)
    page.click('.start.map')
    page.wait_for_selector('#maparea')
    page.wait_for_function('MV.mode === "atlas" || MV.mode === "leaflet"', timeout=20000)
    mode = page.evaluate('MV.mode')
    check('지도 화면 진입(로그인 없음)', True, f'지도 모드={mode}')
    # 실제 클릭으로 핀 추가
    box = page.locator('#mapmount .mapbox, #mapmount .mv').first.bounding_box()
    page.mouse.click(box['x'] + box['width'] * 0.42, box['y'] + box['height'] * 0.45)
    page.wait_for_selector('#pinform')
    page.fill('#f-title', '서울')
    page.fill('#f-desc', '수도')
    page.fill('#f-y', '1950'); page.fill('#f-m', '6'); page.fill('#f-d', '28')
    page.click('[data-act=pin-save]')
    n = page.evaluate('WS.map.pins.length')
    check('지도 클릭으로 핀 추가', n == 1, f'pins={n}')
    pin1 = page.evaluate('WS.map.pins[0]')
    check('핀 데이터 필드(ID·좌표·제목·날짜·생성/수정 시각)', pin1['id'] and pin1['lat'] and pin1['title'] == '서울' and pin1['date'] == {'y': 1950, 'm': 6, 'd': 28} and pin1['createdAt'] and pin1['updatedAt'], json.dumps({k: pin1[k] for k in ['lat', 'lon', 'date']}, ensure_ascii=False))
    # 같은 핸들러로 정확한 좌표의 핀 2개 추가 (인천, 부산) - 부산을 먼저 만들어 생성 순서 ≠ 경로 순서
    for name, lat, lon in [('부산', 35.18, 129.07), ('인천', 37.47, 126.62)]:
        page.evaluate('([a,b]) => { clearSelection(); render(); onMapClick(a,b); }', [lat, lon])
        page.fill('#f-title', name)
        page.click('[data-act=pin-save]')
    ids = page.evaluate('Object.fromEntries(WS.map.pins.map(p=>[p.title,p.id]))')
    check('핀 3개 (서울·부산·인천 순으로 생성)', list(ids.keys()) == ['서울', '부산', '인천'], list(ids.keys()))
    page.screenshot(path=f'{SHOTS}/02-map-pins.png')
    # 경로 1: 서울 → 인천
    page.evaluate('clearSelection(); render()')
    page.click('.map-tools [data-act=route-new]')
    page.wait_for_selector('#routeform')
    page.fill('#f-rname', '서울 → 인천')
    page.click(f'.pickgrid [data-id="{ids["서울"]}"]')
    page.click(f'.pickgrid [data-id="{ids["인천"]}"]')
    page.click('[data-act=route-save]')
    # 경로 2: 인천 → 부산 (지도 위 핀 클릭 핸들러 사용), 색 바꾸기
    page.click('.map-tools [data-act=route-new]')
    page.fill('#f-rname', '인천 → 부산')
    page.evaluate(f'onPinClick(["{ids["인천"]}"])')
    page.evaluate(f'onPinClick(["{ids["부산"]}"])')
    page.click('.swatches [data-id="#9C3A29"]')
    page.click('[data-act=route-save]')
    routes = page.evaluate('WS.map.routes.map(r=>({name:r.name,pinIds:r.pinIds,color:r.color,visible:r.visible}))')
    check('서로 다른 경로 2개를 원하는 순서로 연결', routes[0]['pinIds'] == [ids['서울'], ids['인천']] and routes[1]['pinIds'] == [ids['인천'], ids['부산']], [r['name'] for r in routes])
    check('경로 색 설정', routes[1]['color'] == '#9C3A29')
    pins_json = page.evaluate('JSON.stringify(WS.map.pins)')
    # 경로 순서 바꾸기·핀 추가(다중 경유)
    page.evaluate(f'ACT["route-edit"]("{page.evaluate("WS.map.routes[1].id")}"); render()')
    page.evaluate(f'onPinClick(["{ids["서울"]}"])')
    page.click('.ordlist .ord:nth-child(3) [data-act=rp-up]')
    page.click('[data-act=route-save]')
    r2 = page.evaluate('WS.map.routes[1].pinIds')
    check('다중 경유 + 순서 수정 (인천→서울→부산)', r2 == [ids['인천'], ids['서울'], ids['부산']], r2)
    check('경로를 고쳐도 핀 데이터는 그대로', page.evaluate('JSON.stringify(WS.map.pins)') == pins_json)
    # 표시 끄기
    page.evaluate('S.listTab="routes"; clearSelection(); S.listTab="routes"; render()')
    page.click(f'[data-act=route-vis][data-id="{page.evaluate("WS.map.routes[0].id")}"]')
    check('경로 표시 끄기(기록은 유지)', page.evaluate('WS.map.routes[0].visible') is False and page.evaluate('WS.map.routes.length') == 2)
    # 핀 선택 시 연결 경로 강조
    page.evaluate(f'selectPin("{ids["인천"]}"); render()')
    dec = page.evaluate('mapDecor().lines.map(l=>({n:l.name,hl:l.hl,dim:l.dim}))')
    check('핀을 고르면 그 핀이 든 경로 강조', all(l['hl'] for l in dec), dec)
    page.screenshot(path=f'{SHOTS}/03-map-routes.png')
    # 핀 수정
    page.click('[data-act=pin-edit]')
    page.fill('#f-title', '인천항')
    page.click('[data-act=pin-save]')
    check('핀 수정', page.evaluate(f'pinById("{ids["인천"]}").title') == '인천항')
    # 같은 자리 핀 (인천항 핀 눌러 같은 자리 추가)
    page.evaluate(f'clearSelection(); render(); ACT["mode-add"](); render(); onPinClick(["{ids["인천"]}"])')
    page.fill('#f-title', '월미도 상륙 지점')
    page.click('[data-act=pin-save]')
    spots = page.evaluate('[...pinSpots().values()].map(g=>g.length)')
    check('같은 자리에 핀 2개 저장, 구별해서 선택', 2 in spots, spots)
    page.evaluate(f'clearSelection(); render(); onPinClick(pinSpots().get(spotKey(pinById("{ids["인천"]}"))).map(p=>p.id))')
    check('같은 자리 핀 묶음 목록', page.is_visible('text=같은 자리의 기록 2개'))
    # 핀 삭제 + 되돌리기
    before = page.evaluate('WS.map.routes.map(r=>r.pinIds.length)')
    page.evaluate(f'ACT["pin-del"]("{ids["서울"]}"); render()')
    page.click('[data-act=pin-del-confirm]')
    after = page.evaluate('[WS.map.pins.length, WS.map.routes.map(r=>r.pinIds.length)]')
    check('핀 삭제(경로에서는 그 핀만 빠짐)', after[0] == 3 and after[1] == [1, 2], after)
    page.click('.toast [data-act=undo]')
    check('삭제 되돌리기', page.evaluate('WS.map.pins.length') == 4 and page.evaluate('WS.map.routes.map(r=>r.pinIds.length)') == before)
    # 새로고침 복구
    page.wait_for_timeout(600)
    snap = page.evaluate('JSON.stringify({p:WS.map.pins,r:WS.map.routes})')
    page.reload(); page.wait_for_selector('#maparea')
    check('새로고침 후 지도 복구', page.evaluate('JSON.stringify({p:WS.map.pins,r:WS.map.routes})') == snap)
    check('복구 안내 표시', page.is_visible('text=지난번 작업을 이 기기에서 다시 불러왔어요'))
    # 연표
    page.click('.rail [data-id=timeline]')
    page.wait_for_selector('.tl-main')
    page.click('.tl-head [data-act=ev-add]')
    page.fill('#f-t', '인천상륙작전')
    page.fill('#f-y', '1950'); page.fill('#f-m', '9'); page.fill('#f-d', '15')
    page.fill('#f-desc', '유엔군이 인천에 상륙했다.')
    page.select_option('#f-pin', ids['인천'])
    with page.expect_file_chooser() as fc:
        page.click('#eventform .drop')
    fc.value.set_files(IMG)
    page.wait_for_function('S.draft && S.draft.photo && S.draft.photo.kb', timeout=15000)
    ph = page.evaluate('S.draft.photo')
    check('사진 업로드·압축 미리보기', ph['kb'] <= 1300 and ph['origKb'] > ph['kb'] and max(ph['w'], ph['h']) <= 1600, f"{ph['origKb']}KB → {ph['kb']}KB, {ph['w']}x{ph['h']}")
    check('업로드 미리보기 이미지 표시', page.evaluate('!!document.querySelector("#eventform .photo-big img").src.startsWith("blob:")'))
    page.fill('#f-pcap', '상륙정'); page.fill('#f-pcred', '미 해군 · 퍼블릭 도메인')
    page.fill('#f-src', '교과서 120쪽')
    page.click('[data-act=ev-save]')
    e1 = page.evaluate('WS.tl.events[0]')
    check('사건 저장(사진 설명·출처·관련 장소 포함)', e1['t'] == '인천상륙작전' and e1['photo']['caption'] == '상륙정' and e1['pinId'] == ids['인천'] and e1['place']['name'] == '인천항', e1['place'])
    # 날짜 미상 · 대략 · 장소 검색 대신 직접 좌표 없음
    for t, y, m, unk, *dd in [('서울 수복', '1950', '9', False, '28'), ('정전협정', '1953', '7', False, '27'), ('피란 기록(날짜 모름)', '', '', True, '')]:
        page.click('.tl-head [data-act=ev-add]')
        page.fill('#f-t', t)
        if unk: page.check('#f-unknown')
        else: page.fill('#f-y', y); page.fill('#f-m', m); page.fill('#f-d', dd[0])
        page.click('[data-act=ev-save]')
    order = page.evaluate('sorted().map(e=>e.t)')
    check('날짜순 정렬(날짜 미상은 맨 뒤)', order == ['인천상륙작전', '서울 수복', '정전협정', '피란 기록(날짜 모름)'], order)
    # 잘못된 날짜 검증
    page.click('.tl-head [data-act=ev-add]')
    page.fill('#f-t', '오류 테스트'); page.fill('#f-y', '1950'); page.fill('#f-m', '2'); page.fill('#f-d', '31')
    page.click('[data-act=ev-save]')
    check('없는 날짜(2월 31일) 막기', page.is_visible('text=2월은 28일까지 있어요.'))
    page.click('[data-act=ev-cancel]')
    # 관계 잇기
    eid = {e['t']: e['id'] for e in page.evaluate('WS.tl.events')}
    page.evaluate(f'ACT["ev-sel"]("{eid["인천상륙작전"]}"); render()')
    page.select_option('#q-relto', eid['서울 수복'])
    page.click('[data-act=rel-add]')
    check('사건 관계 잇기', page.evaluate('WS.tl.rels.length') == 1)
    # 디자인 전환 데이터 보존
    before = page.evaluate('JSON.stringify({e:WS.tl.events,r:WS.tl.rels})')
    page.screenshot(path=f'{SHOTS}/04-tl-museum.png')
    page.click('[data-act=design][data-id=cards]')
    page.click('[data-act=toggle-rel]')
    page.wait_for_timeout(200)
    page.screenshot(path=f'{SHOTS}/05-tl-cards.png')
    check('디자인 2(기록 카드형) 전환', page.is_visible('.tlB') and page.evaluate('WS.tl.design') == 'cards')
    check('기록 카드형 관계 선 표시', page.evaluate('!!document.querySelector(".relsB path")'))
    page.click('[data-act=design][data-id=museum]')
    check('디자인 1로 돌아와도 데이터 동일', page.evaluate('JSON.stringify({e:WS.tl.events,r:WS.tl.rels})') == before and page.is_visible('.tlA'))
    # 사진 교체·삭제
    page.evaluate(f'ACT["ev-sel"]("{eid["인천상륙작전"]}"); ACT["ev-edit"](); render()')
    old = page.evaluate('S.draft.photo.id')
    with page.expect_file_chooser() as fc:
        page.click('#eventform .photo-big label')
    fc.value.set_files(IMG)
    page.wait_for_function(f'S.draft.photo && S.draft.photo.id !== "{old}"', timeout=15000)
