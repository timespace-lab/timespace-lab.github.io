"""계정 저장 흐름 (테스트용 가짜 Supabase 주입): 로그인 후 저장, 불러오기, 충돌, 네트워크 오류, 로그인 취소·만료, 공유"""
import json, sys
from playwright.sync_api import sync_playwright
BASE, SHOTS, IMG = sys.argv[1], sys.argv[2], sys.argv[3]
MOCK = open('test/mock-supabase.js', encoding='utf8').read()
results = []
def check(name, cond, detail=''):
    results.append((name, bool(cond))); print(('PASS ' if cond else 'FAIL ') + name + (' · ' + str(detail) if detail else ''))
def flags(page, **kw): page.evaluate('f => localStorage.setItem("mock.sb.flags", JSON.stringify(f))', kw)
def mockdb(page): return page.evaluate('JSON.parse(localStorage.getItem("mock.sb.db")||"{\\"rows\\":[],\\"files\\":{}}")')

with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 1440, 'height': 900})
    ctx.add_init_script(MOCK)
    page = ctx.new_page(); errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(BASE + '/index.html'); page.wait_for_function('S.cloudReady')
    page.evaluate('loadSampleNow(); render()'); page.wait_for_selector('#maparea'); page.wait_for_timeout(500)
    pins0 = page.evaluate('JSON.stringify(WS.map.pins)')
    page.click('.topbar [data-act=cloud-save]')
    check('로그인 전 저장 → 로그인 안내', page.is_visible('text=Google로 로그인') and page.is_visible('text=이어서 계정에 저장해요'))
    page.screenshot(path=f'{SHOTS}/20-login.png')
    with page.expect_navigation():
        page.click('[data-act=login-google]')
    page.wait_for_function('S.cloudReady && S.user', timeout=10000)
    page.wait_for_function('WS.map.cloudId', timeout=10000)
    check('로그인 후 지도를 이어서 계정에 저장', page.evaluate('WS.map.cloudId && !WS.map.dirty'), page.evaluate('S.cloud.map'))
    check('로그인 리디렉트 뒤 주소 정리(?code 제거)', '?code' not in page.url, page.url)
    check('저장 후 상태 표시 "계정에 저장됨"', page.is_visible('#savestat >> text=계정에 저장됨'))
    check('저장된 행에 핀·경로 데이터', len(mockdb(page)['rows'][0]['data']['pins']) == 7 and len(mockdb(page)['rows'][0]['data']['routes']) == 2)
    check('로그인 전후 지도 데이터 동일', page.evaluate('JSON.stringify(WS.map.pins)') == pins0)
    # 연표에 사진 넣고 저장 → 스토리지 업로드
    page.click('.rail [data-id=timeline]'); page.wait_for_selector('.tl-main')
    page.click('.tl-head [data-act=ev-add]'); page.fill('#f-t', '사진 업로드 시험'); page.fill('#f-y', '1952')
    with page.expect_file_chooser() as fc: page.click('#eventform .drop')
    fc.value.set_files(IMG); page.wait_for_function('S.draft.photo && S.draft.photo.kb', timeout=15000)
    page.click('[data-act=ev-save]')
    page.click('.topbar [data-act=cloud-save]'); page.wait_for_function('S.cloud.tl.status==="saved"', timeout=15000)
    db = mockdb(page)
    tlrow = [r for r in db['rows'] if r['kind'] == 'timeline'][0]
    up = [e for e in tlrow['data']['events'] if e['t'] == '사진 업로드 시험'][0]
    check('사진은 스토리지에, DB에는 경로만', up['photo']['path'] in db['files'] and up['photo']['path'] in tlrow['photo_paths'] and 'data:image' not in json.dumps(tlrow['data']), up['photo']['path'])
    check('사진 경로가 내 폴더(<uid>/...)', up['photo']['path'].startswith('user-1/'))
    # 다시 저장 → version 증가
    page.fill('#q-title', '6·25 전쟁 복습 (수정)'); page.wait_for_timeout(500)
    check('제목 고치면 "저장 안 된 변경"', page.is_visible('#savestat >> text=저장 안 된 변경'))
    page.click('.topbar [data-act=cloud-save]'); page.wait_for_function('S.cloud.tl.status==="saved" && !WS.tl.dirty', timeout=10000)
    v = [r for r in mockdb(page)['rows'] if r['kind'] == 'timeline'][0]
    check('기존 탐구 수정 후 다시 저장(version 2)', v['version'] == 2 and v['title'] == '6·25 전쟁 복습 (수정)')
    # 중복 클릭: 저장 중 버튼 비활성
    page.evaluate('WS.tl.desc="x"; touch("tl")')
    page.evaluate('Cloud.saveLayer("tl"); Cloud.saveLayer("tl")')
    page.wait_for_function('S.cloud.tl.status==="saved"', timeout=10000)
    v2 = [r for r in mockdb(page)['rows'] if r['kind'] == 'timeline'][0]['version']
    check('저장 중 중복 요청은 한 번만 처리', v2 == 3, v2)
    # 충돌: 다른 기기가 먼저 저장
    page.evaluate('''() => { const d = JSON.parse(localStorage.getItem("mock.sb.db")); d.rows.find(r=>r.kind==="timeline").version = 9; localStorage.setItem("mock.sb.db", JSON.stringify(d)); WS.tl.desc="충돌 테스트"; touch("tl"); }''')
    page.click('.topbar [data-act=cloud-save]')
    page.wait_for_selector('text=다른 곳에서 먼저 바뀌었어요')
    check('다른 기기에서 먼저 저장된 경우 충돌 안내', True)
    page.click('[data-act=cloud-overwrite]'); page.wait_for_function('S.cloud.tl.status==="saved"', timeout=10000)
    check('덮어쓰기 선택 시 저장', [r for r in mockdb(page)['rows'] if r['kind'] == 'timeline'][0]['version'] == 10)
    # 네트워크 오류
    flags(page, offline=True)
    page.evaluate('WS.tl.desc="오프라인 수정"; touch("tl")'); page.wait_for_timeout(400)
    page.click('.topbar [data-act=cloud-save]'); page.wait_for_function('S.cloud.tl.status==="failed"', timeout=10000)
    check('네트워크 오류: 실패 표시', page.is_visible('text=인터넷 연결이 끊겨 계정에 저장하지 못했어요') and page.is_visible('#savestat >> text=계정 저장 실패'))
    check('네트워크 오류: 로컬 데이터 유지·저장됨 표시 안 함', page.evaluate('WS.tl.desc') == '오프라인 수정' and page.evaluate('WS.tl.dirty') and not page.is_visible('#savestat >> text=계정에 저장됨'))
    page.screenshot(path=f'{SHOTS}/21-save-failed.png')
    page.reload(); page.wait_for_function('S.cloudReady')
    check('네트워크 오류 뒤 새로고침해도 로컬 유지', page.evaluate('WS.tl.desc') == '오프라인 수정')
    flags(page)
    page.click('.topbar [data-act=cloud-save]'); page.wait_for_function('S.cloud.tl.status==="saved"', timeout=10000)
    check('연결 복구 후 다시 저장', not page.evaluate('WS.tl.dirty'))
    # 로그인 만료
    flags(page, expired=True)
    page.evaluate('WS.tl.desc="만료 테스트"; touch("tl")')
    page.click('.topbar [data-act=cloud-save]'); page.wait_for_function('S.cloud.tl.status==="failed"', timeout=10000)
    check('로그인 만료: 다시 로그인 안내 + 데이터 유지', page.is_visible('text=로그인이 만료됐어요') and page.evaluate('WS.tl.desc') == '만료 테스트' and page.evaluate('S.dialog') == 'login')
    page.click('[data-act=login-cancel]')
    flags(page)
    # 내 탐구 목록과 불러오기
    page.click('.rail [data-id=library]'); page.wait_for_function('S.lib.status==="done"')
    check('내 탐구: 계정에 저장한 지도 목록', page.locator('.lcard [data-act=lib-open]').count() == 1)
    page.screenshot(path=f'{SHOTS}/22-library.png')
    mapid = page.evaluate('WS.map.cloudId')
    page.evaluate('WS.map.pins.pop(); touch("map")'); page.wait_for_timeout(400)
    page.click(f'[data-act=lib-open][data-id="{mapid}"]')
    page.wait_for_selector('text=계정에 저장된 판으로 되돌릴까요?')
    page.click('[data-act=lib-open-confirm]'); page.wait_for_selector('#maparea')
    page.wait_for_timeout(300)
    check('저장된 지도 불러오기(로컬 변경 확인 후)', page.evaluate('WS.map.pins.length') == 7 and not page.evaluate('WS.map.dirty'))
    # 다른 지도로 새로 시작 후 불러오기 → 되돌리기 가능
    page.evaluate('startNew("map"); render()')
    check('새 지도 시작(이전 작업은 되돌리기 가능)', page.evaluate('WS.map.pins.length') == 0)
    page.evaluate('setRoute("library"); render()'); page.wait_for_function('S.lib.status==="done"')
    page.click(f'[data-act=lib-open][data-id="{mapid}"]'); page.wait_for_selector('#maparea')
    check('빈 지도에서 저장된 지도 바로 불러오기', page.evaluate('WS.map.pins.length') == 7)
    # 공유
    page.click('.topbar [data-act=share]')
    page.click('[data-act=share-toggle]'); page.wait_for_function('S.dialogData.mode==="view"')
    page.click('[data-act=perm][data-id=copy]'); page.wait_for_function('S.dialogData.mode==="copy"')
    link = page.input_value('#q-sharelink')
    check('공유 링크 만들기(복사 허용)', '?view=' in link and mockdb(page)['rows'][0]['share_mode'] == 'copy', link)
    page.screenshot(path=f'{SHOTS}/23-share.png')
    # 다른 사용자(로그인 안 함)가 공유 링크 열기
    tl_id = page.evaluate('WS.tl.cloudId')
    page.evaluate('WS.tl.cloudId && Cloud.setShare("tl","copy")'); page.wait_for_timeout(300)
    dbdump = json.dumps(mockdb(page))
    ctx2 = b.new_context(viewport={'width': 1440, 'height': 900}); ctx2.add_init_script(MOCK)
    ctx2.add_init_script('localStorage.getItem("mock.sb.db") || localStorage.setItem("mock.sb.db", ' + json.dumps(dbdump) + ')')
    p2 = ctx2.new_page(); p2.on('pageerror', lambda e: errors.append('viewer:' + str(e)))
    p2.goto(BASE + f'/index.html?view={tl_id}'); p2.wait_for_function('S.view', timeout=10000)
    check('공유 링크: 로그인 없이 보기 전용으로 열림', p2.evaluate('S.view.kind') == 'timeline' and p2.is_visible('text=보기 전용이에요'))
    p2.wait_for_timeout(600)
    shown = p2.evaluate('''() => { const e = S.view.layer.events.find(x=>x.t==="사진 업로드 시험"); const im = document.querySelector(`img[data-pid="${e.photo.id}"]`); return !!(im && im.src.startsWith("data:image/jpeg") && im.naturalWidth>0); }''')
    check('공유 보기: 계정 스토리지 사진 표시', shown)
    p2.screenshot(path=f'{SHOTS}/24-shared-view.png')
    p2.click('.tl-head [data-act=design][data-id=cards]')
    p2.evaluate('ACT["ev-sel"](S.view.layer.events[0].id); render()')
    blocked = p2.evaluate('!document.querySelector(".insp [data-act=ev-edit]")')
    check('공유 보기: 편집 버튼 없음', blocked)
    check('공유 보기는 받은 사람 기기 작업과 섞이지 않음', p2.evaluate('WS.tl.events.length') == 0)
    p2.click('[data-act=view-copy]'); p2.wait_for_function('!S.view', timeout=10000)
    cp = p2.evaluate('[WS.tl.events.length, WS.tl.title, WS.tl.cloudId, !!WS.tl.events.find(e=>e.photo && !e.photo.key && !e.photo.path)]')
    check('복사 허용 링크: 내 기기로 사본 가져오기(사진 포함)', cp[0] == 11 and '(사본)' in cp[1] and cp[2] is None and cp[3], cp)
    ctx2.close()
    # 로그아웃 후에도 로컬 유지
    page.evaluate('Cloud.signOut()'); page.wait_for_timeout(300)
    check('로그아웃해도 이 기기 작업 유지', page.evaluate('WS.map.pins.length') == 7 and page.evaluate('S.user') is None)
    # 로그인 취소
    ctx3 = b.new_context(viewport={'width': 1200, 'height': 860}); ctx3.add_init_script(MOCK)
    p3 = ctx3.new_page(); p3.on('pageerror', lambda e: errors.append('cancel:' + str(e)))
    p3.goto(BASE + '/index.html'); p3.wait_for_function('S.cloudReady')
    p3.evaluate('loadSampleNow(); render()'); p3.wait_for_timeout(400)
    flags(p3, cancelLogin=True)
    before = p3.evaluate('JSON.stringify([WS.map, WS.tl].map(l=>[l.pins||l.events]))')
    p3.click('.topbar [data-act=cloud-save]')
    with p3.expect_navigation(): p3.click('[data-act=login-google]')
    p3.wait_for_function('S.cloudReady'); p3.wait_for_timeout(300)
    check('로그인 취소: 안내 + 데이터 유지', p3.is_visible('text=로그인하지 못했어요') and p3.evaluate('JSON.stringify([WS.map, WS.tl].map(l=>[l.pins||l.events]))') == before and p3.evaluate('S.user') is None)
    check('로그인 취소 뒤에도 원래 화면으로 복귀', p3.evaluate('S.route') == 'map')
    p3.screenshot(path=f'{SHOTS}/25-login-cancel.png')
    ctx3.close()
    check('스크립트 오류 없음', not errors, errors[:5])
    b.close()
print('\nSUMMARY', sum(1 for r in results if r[1]), '/', len(results))
